"""Compare chunk sizes and calibrate the refusal threshold on data/eval/rag_questions.yaml.

For each chunking config:
  - hit@1 / hit@k: is a chunk from the expected manual section among the top-1 / top-k?
  - MRR: mean reciprocal rank of the first chunk from the expected section.
  - top-1 cosine for in-domain vs out-of-domain questions.
For the chosen config, every threshold between the two score populations is scanned and the one
with the best balanced accuracy (answer in-domain, refuse out-of-domain) is reported.

    uv run python scripts/eval_retrieval.py      # writes reports/retrieval_eval.md
"""

from __future__ import annotations

import logging
import sys
from dataclasses import replace
from pathlib import Path

import numpy as np
import yaml

from support_copilot.rag.config import RagSettings
from support_copilot.rag.ingest import embeddings, load_or_build
from support_copilot.rag.retriever import ManualRetriever

logger = logging.getLogger("eval_retrieval")
QUESTIONS = Path("data/eval/rag_questions.yaml")
OUT = Path("reports/retrieval_eval.md")
CONFIGS = [(500, 75), (1000, 150), (1500, 225)]
K = 4


def evaluate(retriever: ManualRetriever, in_domain: list[dict], out_domain: list[str]) -> dict:
    ranks, top1_in, misses = [], [], []
    for item in in_domain:
        hits = retriever.search(item["q"], k=K)
        top1_in.append(hits[0].score)
        rank = next((i + 1 for i, h in enumerate(hits) if h.section == item["section"]), None)
        ranks.append(rank)
        if rank != 1:
            misses.append((item["q"], item["section"], hits[0].section, rank))
    top1_out = [retriever.search(q, k=1)[0].score for q in out_domain]
    hit1 = float(np.mean([r == 1 for r in ranks]))
    hitk = float(np.mean([r is not None for r in ranks]))
    mrr = float(np.mean([1 / r if r else 0 for r in ranks]))
    return {
        "hit1": hit1,
        "hitk": hitk,
        "mrr": mrr,
        "in": np.array(top1_in),
        "out": np.array(top1_out),
        "misses": misses,
    }


def best_threshold(scores_in: np.ndarray, scores_out: np.ndarray) -> tuple[float, float, float, float]:
    """Threshold maximising balanced accuracy; ties -> midpoint of the widest gap."""
    candidates = np.unique(np.concatenate([scores_in, scores_out]))
    best = (-1.0, 0.0, 0.0, 0.0)
    for t in candidates:
        tpr = float(np.mean(scores_in >= t))  # in-domain answered
        tnr = float(np.mean(scores_out < t))  # out-of-domain refused
        bal = (tpr + tnr) / 2
        if bal > best[0]:
            best = (bal, float(t), tpr, tnr)
    bal, t, tpr, tnr = best
    lower = scores_out[scores_out < t]
    if lower.size:  # move to the middle of the gap for margin on unseen questions
        t = (float(lower.max()) + t) / 2
    return t, bal, tpr, tnr


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    data = yaml.safe_load(QUESTIONS.read_text(encoding="utf-8"))
    base = RagSettings()
    emb = embeddings(base)

    rows, results = [], {}
    for size, overlap in CONFIGS:
        s = replace(base, chunk_size=size, chunk_overlap=overlap)
        store = load_or_build(s, emb)
        res = evaluate(ManualRetriever(store, K, s.min_score), data["in_domain"], data["out_of_domain"])
        results[(size, overlap)] = res
        rows.append((size, overlap, store.index.ntotal, res))
        logger.info(
            "chunk=%d/%d n=%d hit@1=%.3f hit@%d=%.3f mrr=%.3f",
            size,
            overlap,
            store.index.ntotal,
            res["hit1"],
            K,
            res["hitk"],
            res["mrr"],
        )

    chosen = max(rows, key=lambda r: (r[3]["mrr"], r[3]["hitk"]))
    size, overlap, n, res = chosen
    t, bal, tpr, tnr = best_threshold(res["in"], res["out"])

    lines = [
        "# Retrieval evaluation",
        "",
        f"Generated by `scripts/eval_retrieval.py` · {len(data['in_domain'])} in-domain questions (expected manual "
        f"section) · {len(data['out_of_domain'])} out-of-domain · embeddings `{base.embedding_model}` · cosine · k={K}",
        "",
        "## Chunk size",
        "",
        f"| chunk / overlap | chunks | hit@1 | hit@{K} | MRR | top-1 cos in-domain (mean) "
        "| top-1 cos out-of-domain (max) |",
        "|---|---|---|---|---|---|---|",
    ]
    for sz, ov, nn, r in rows:
        mark = " **(chosen)**" if (sz, ov) == (size, overlap) else ""
        lines.append(
            f"| {sz} / {ov}{mark} | {nn} | {r['hit1']:.3f} | {r['hitk']:.3f} | {r['mrr']:.3f} | "
            f"{r['in'].mean():.3f} | {r['out'].max():.3f} |"
        )
    lines += [
        "",
        "Chosen = highest MRR (ties: hit@k).",
        "",
        "## Refusal threshold (chosen config)",
        "",
        f"- In-domain top-1 cosine: min {res['in'].min():.3f} · median {np.median(res['in']):.3f}",
        f"- Out-of-domain top-1 cosine: median {np.median(res['out']):.3f} · max {res['out'].max():.3f}",
        f"- **Threshold {t:.3f}**: answers {tpr:.0%} of in-domain, refuses {tnr:.0%} of out-of-domain "
        f"(balanced accuracy {bal:.3f})",
        "",
        "## Misses at rank 1 (chosen config)",
        "",
        "| question | expected | top-1 section | rank of expected |",
        "|---|---|---|---|",
    ]
    for q, exp, got, rank in res["misses"]:
        lines.append(f"| {q} | {exp} | {got} | {rank or f'> {K}'} |")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    logger.info("written %s · chosen %d/%d · threshold %.3f", OUT, size, overlap, t)
    return 0


if __name__ == "__main__":
    sys.exit(main())
