"""Does personal data in a ticket change the triage? And what should the classifier see?

The training/test sets have no personal data (anonymised), but real tickets end with a signature.
Each test ticket gets a synthetic contact line (fake names, e-mail, phone; 5 seeds) and is classified
three ways: raw, PII masked with typed placeholders ([EMAIL]...), PII stripped.

Writes reports/triage_pii.md. Run: uv run python scripts/eval_triage_pii.py
"""

from __future__ import annotations

import logging
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import f1_score

from support_copilot.api.classifier import TicketClassifier
from support_copilot.guardrails import mask_pii, strip_pii

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
log = logging.getLogger("eval_triage_pii")

SEEDS = range(5)
FIRST = ["maria", "joao", "ana", "pedro", "lucas", "julia", "carlos", "fernanda", "rafael", "beatriz"]
LAST = ["silva", "souza", "oliveira", "santos", "lima", "costa", "pereira", "almeida"]
OUT = Path("reports/triage_pii.md")


def contact_line(rng: np.random.Generator) -> str:
    f, la = rng.choice(FIRST), rng.choice(LAST)
    phone = f"(19) 9{rng.integers(1000, 9999)}-{rng.integers(1000, 9999)}"
    return [
        f" Contact: {f}.{la}@example.com",
        f" Best regards, {f.title()} {la.title()} - {f}.{la}@example.com - {phone}",
        f" You can reach me at {f}{rng.integers(10, 99)}@gmail.com",
    ][rng.integers(3)]


def main() -> None:
    clf = TicketClassifier.load(Path("models"))
    labels, tech = np.array(clf.labels), set(clf.technical)
    test = pd.read_parquet("data/processed/test.parquet")
    y, y_tech = test.label.to_numpy(), test.is_technical.to_numpy()
    with_pii = sum(mask_pii(t).found for t in test.text)

    def predict(texts: list[str]) -> np.ndarray:  # the pipeline directly: no stripping inside
        return labels[clf.pipeline.predict(texts)]

    def route(pred: np.ndarray) -> np.ndarray:
        return np.isin(pred, list(tech))

    clean = predict(test.text.tolist())
    rows = []
    for seed in SEEDS:
        rng = np.random.default_rng(seed)
        aug = [t + contact_line(rng) for t in test.text]
        variants = {
            "raw": aug,
            "masked [EMAIL]": [mask_pii(t).text for t in aug],
            "stripped": [strip_pii(t) for t in aug],
        }
        for name, texts in variants.items():
            p = predict(texts)
            rows.append(
                {
                    "seed": seed,
                    "variant": name,
                    "f1_macro": f1_score(y, p, average="macro"),
                    "routing_f1": f1_score(y_tech, route(p), average="macro"),
                    "route_flips": int((route(p) != route(clean)).sum()),
                    "to_customer_service": int(((p == "Customer Service") & (clean != "Customer Service")).sum()),
                }
            )
        log.info("seed %d done", seed)
    r = pd.DataFrame(rows)
    agg = r.groupby("variant", sort=False).agg(["mean", "std"])
    paired = r.pivot(index="seed", columns="variant", values="f1_macro")

    def ms(v: str, col: str, fmt: str = ".4f") -> str:
        return f"{agg.loc[v, (col, 'mean')]:{fmt}} ± {agg.loc[v, (col, 'std')]:{fmt}}"

    lines = [
        "# Triage robustness to personal data",
        "",
        f"Generated by `scripts/eval_triage_pii.py` · test set {len(test)} tickets · texts with PII in the "
        f"test set: {with_pii} · synthetic contact line appended (fake names, e-mail, phone) · seeds 0–4.",
        "",
        f"Clean test set (no contact line): F1 macro {f1_score(y, clean, average='macro'):.4f} · "
        f"routing F1 {f1_score(y_tech, route(clean), average='macro'):.4f}",
        "",
        "| what the classifier sees | F1 macro | routing F1 | route flips vs clean | new → Customer Service |",
        "|---|---|---|---|---|",
    ]
    for v in agg.index:
        lines.append(
            f"| {v} | {ms(v, 'f1_macro')} | {ms(v, 'routing_f1')} | {ms(v, 'route_flips', '.0f')} | "
            f"{ms(v, 'to_customer_service', '.0f')} |"
        )
    lines += [
        "",
        "Paired by seed, F1 macro minus raw: "
        f"masked {(paired['masked [EMAIL]'] - paired['raw']).round(4).tolist()} · "
        f"stripped {(paired['stripped'] - paired['raw']).round(4).tolist()}",
        "",
        "**Decision:** the classifier sees the stripped text (`strip_pii`); the RAG keeps the typed "
        "placeholders. See `docs/findings.md` §7.",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    log.info("written %s", OUT)


if __name__ == "__main__":
    main()
